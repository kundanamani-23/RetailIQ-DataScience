import pandas as pd
import os

# -----------------------------------
# Load integrated dataset
# -----------------------------------
file_path = "outputs/integrated/retailiq_master.csv"

df = pd.read_csv(file_path)

# Convert dates
df["order_date"] = pd.to_datetime(df["order_date"])
df["customer_signup_date"] = pd.to_datetime(
    df["customer_signup_date"]
)
df["last_order_date"] = pd.to_datetime(
    df["last_order_date"]
)
df["product_launch_date"] = pd.to_datetime(
    df["product_launch_date"]
)


# -----------------------------------
# TIME FEATURES
# -----------------------------------

df["order_year"] = df["order_date"].dt.year
df["order_month"] = df["order_date"].dt.month
df["order_month_name"] = df["order_date"].dt.month_name()
df["order_quarter"] = df["order_date"].dt.quarter
df["order_day"] = df["order_date"].dt.day
df["order_day_name"] = df["order_date"].dt.day_name()


# -----------------------------------
# SALES FEATURES
# -----------------------------------

# Revenue generated by each order item
df["revenue"] = df["item_revenue"]

# Profit from each order item
df["item_profit"] = df["profit"]

# Profit margin percentage
df["profit_margin"] = (
    df["item_profit"] / df["revenue"] * 100
)

# Avoid infinite values
df["profit_margin"] = df["profit_margin"].replace(
    [float("inf"), float("-inf")], 0
)


# -----------------------------------
# CUSTOMER FEATURES
# -----------------------------------

# Customer age at signup
df["customer_age"] = df["age"]

# Customer lifetime in days
df["customer_lifetime_days"] = (
    df["order_date"] - df["customer_signup_date"]
).dt.days

# Avoid negative values
df["customer_lifetime_days"] = df[
    "customer_lifetime_days"
].clip(lower=0)


# -----------------------------------
# PRODUCT FEATURES
# -----------------------------------

# Inventory value
df["inventory_value"] = (
    df["stock_quantity"] * df["cost_price"]
)

# Product profit per unit
df["profit_per_unit"] = (
    df["price"] - df["cost_price"]
)


# -----------------------------------
# DISCOUNT FEATURES
# -----------------------------------

df["discount_amount"] = (
    df["unit_price"]
    * df["quantity"]
    * df["discount_percentage_item"]
    / 100
)


# -----------------------------------
# RETURN FLAG
# -----------------------------------

# Load returns data to identify orders with returns
returns = pd.read_csv("outputs/cleaned/returns_cleaned.csv")

# Get unique order IDs that have at least one return
returned_orders = set(returns["order_id"].unique())

# Flag orders: 1 if the order had a return, 0 otherwise
df["has_return"] = df["order_id"].apply(
    lambda x: 1 if x in returned_orders else 0
)


# -----------------------------------
# OUTPUT
# -----------------------------------

os.makedirs("outputs/features", exist_ok=True)

output_file = "outputs/features/retailiq_features.csv"

df.to_csv(output_file, index=False)


